local hostname = hostname_file and hostname_file:read("*l") or ""
if hostname_file then
    hostname_file:close()
end

if hostname == "t480" then
    hl.device({
        name       = "at-translated-set-2-keyboard",
        kb_layout  = "br",
        kb_variant = "thinkpad",
    })
end


