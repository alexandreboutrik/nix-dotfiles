hl.on("hyprland.start", function()
    hl.exec_cmd("waybar & hyprpaper")

    -- Spawn startup apps on specific workspaces
    hl.dispatch(hl.dsp.exec_cmd(terminal, { workspace = "1" }))
    hl.dispatch(hl.dsp.exec_cmd(terminal, { workspace = "2" }))
    hl.dispatch(hl.dsp.exec_cmd(terminal, { workspace = "2" }))
    hl.dispatch(hl.dsp.exec_cmd(browser,  { workspace = "9" }))
end)

-- Override keyboard layout if hostname is t480
